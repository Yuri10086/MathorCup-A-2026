#!/usr/bin/env python3
# coding: utf-8
"""Optional constrained counterfactual enhancement: Gaussian target candidates + OT proposal.
Preserves all 4 measured no-worsening conditions and frozen stale_hops proxy.
The defect criteria are on proxies, so laboratory validation is still required.
AI-assisted OpenAI GPT-6 (2026-10-27), human audit mandatory.
"""
from pathlib import Path
import argparse,json
import numpy as np,pandas as pd
from q3_complete import Transformer,StyleGaussian,ot_matrix,fit_sensory,SEED

def main():
 ap=argparse.ArgumentParser();ap.add_argument('--data-dir',default='/mnt/data');ap.add_argument('--q1-reference',default='/mnt/data/q1_rebuild/results/reference_raw_panel_means_250.csv');ap.add_argument('--results',default='/mnt/data/MathorCup_A_Q3_Submission/results');a=ap.parse_args()
 o=Path(a.results);root=Path(a.data_dir)
 df=pd.read_csv(next(iter(sorted(root.glob('1*.csv')))))
 yf=pd.read_csv(next(iter(sorted(root.glob('4*.csv')))))
 chem=list(df.columns[3:]);target=list(yf.columns[3:]);style=df.tasting_category_fine.to_numpy(str);X=df[chem].to_numpy(float)
 Y=pd.read_csv(a.q1_reference,encoding='utf-8-sig')[target].to_numpy(float)
 pred=fit_sensory(X,Y)
 t=Transformer(12).fit(X);z=t.encode(X);gauss=StyleGaussian().fit(z,style,sorted(np.unique(style).tolist()))
 source_ids=np.flatnonzero(style=='Pils/Lager');srcraw=X[source_ids];src=t.imp.transform(srcraw)
 mu_idx=[chem.index(q) for q in ['DMS','X2.3.butanedione','X4VG','X.E..2.nonenal']]
 for j in mu_idx:src[np.isnan(srcraw[:,j]),j]=t.low[j]
 zs=t.encode(src)
 mu=gauss.means['Tripel'];mat=ot_matrix(gauss.covs['Pils/Lager'],gauss.covs['Tripel'])
 ot=t.decode(mu+(zs-gauss.means['Pils/Lager'])@mat.T)
 rg=np.random.default_rng(SEED+711)
 # all candidate target draws are generated by THE SAME fitted style-conditional distribution
 tripel_draws=t.decode(gauss.sample('Tripel',100,rg))
 j4=[chem.index(x) for x in ['DMS','X2.3.butanedione','X4VG','X.E..2.nonenal']]
 stale_idx=target.index('stale_hops')
 origin_stale=pred(src)[:,stale_idx]
 candidates=[];metadata=[]
 alphas=[.10,.25,.50,.75,1.0]
 for i in range(len(src)):
    proposals=np.vstack([ot[i:i+1],tripel_draws]);n=len(proposals)
    # clip before interpolation: every point on line segment inherits direct chemical nonworsening
    proposals[:,j4]=np.minimum(proposals[:,j4],src[i,j4])
    x=(src[i:i+1,None,:] + np.array(alphas)[None,:,None]*(proposals[:,None,:]-src[i:i+1,None,:])).reshape(-1,len(chem))
    candidates.append(x)
    metadata.extend([(i,j,float(alphas[k])) for j in range(n) for k in range(len(alphas))])
 cand=np.vstack(candidates)
 sta=pred(cand)[:,stale_idx]
 zz=t.encode(cand)
 orig_style_dist=np.linalg.norm(zs-mu,axis=1)
 # candidates are chosen strictly by a predeclared smooth objective: balance Tripel resemblance and small source perturbation.
 choice=[];alpha=[];cl=[];source_rows=[];rows=[];start=0
 for i in range(len(src)):
    nrows=len(candidates[i]);ls=np.arange(start,start+nrows);start+=nrows
    curz=zz[ls];dist=np.linalg.norm(curz-mu,axis=1)
    travel=np.linalg.norm(curz-zs[i],axis=1)
    hard_safe=(sta[ls] <=origin_stale[i]+1e-10)&(dist < orig_style_dist[i]-1e-4)
    # prioritize transport advantage, control source drift; disallow overly large jumps (>6 standard latent units)
    feasible=np.flatnonzero(hard_safe &(travel<6))
    if len(feasible):
        scores=dist[feasible]+.15*travel[feasible]
        ix=ls[feasible[np.argmin(scores)]]
        chosen=cand[ix]
        aa=metadata[ix][2];ci=metadata[ix][1]
    else:
        chosen=src[i].copy();aa=0.;ci=-1
    d=np.linalg.norm(t.encode(chosen[None,:])[0]-mu)
    assert np.isfinite(chosen).all() and (chosen[j4]<=src[i,j4]+1e-10).all()
    assert pred(chosen[None,:])[0,stale_idx]<=origin_stale[i]+1e-10
    rows.append({'beer':int(df.beer.iloc[source_ids[i]]),'original_row':int(source_ids[i]+1),
        'chosen_proposal':'ot' if ci==0 else ('conditional_target_sample' if ci>0 else 'unchanged'),
        'blend_alpha':aa,'distance_to_target_before':orig_style_dist[i],
        'distance_to_target_after':d,'source_stale_predicted':origin_stale[i],
        'after_stale_predicted':pred(chosen[None,:])[0,stale_idx]})
    choice.append(chosen)
 res=np.asarray(choice)
 pd.DataFrame(rows).to_csv(o/'pils_to_tripel_optimized_audit_11.csv',index=False)
 pd.DataFrame(res,columns=chem).assign(source_beer=df.beer.iloc[source_ids].values).to_csv(o/'pils_to_tripel_optimized_chemical231.csv',index=False)
 sensory=pred(res)
 pd.DataFrame(sensory,columns=target).assign(source_beer=df.beer.iloc[source_ids].values).to_csv(o/'pils_to_tripel_optimized_sensory_0to6.csv',index=False)
 # Compare to previous linear only transport and exact safety verification
 old=pd.read_csv(o/'pils_to_tripel_defect_audit_11.csv')
 new=pd.DataFrame(rows)
 s={'original_OT':{'n_moved':int((old.transport_alpha>1e-6).sum()),'n_closer':int((old.dist_to_tripel_after < old.dist_to_tripel_before-1e-4).sum()),
                   'mean_distance_before':float(old.dist_to_tripel_before.mean()),'mean_distance_after':float(old.dist_to_tripel_after.mean())},
    'optimized':{'n_moved':int((new.blend_alpha>0).sum()),'n_closer':int((new.distance_to_target_after < new.distance_to_target_before-1e-4).sum()),
                 'mean_distance_before':float(new.distance_to_target_before.mean()),'mean_distance_after':float(new.distance_to_target_after.mean()),
                 'chemical_nonworsening_violations':int((res[:,j4]>src[:,j4]+1e-10).sum()),
                 'unverifiable_missing_source_defects':int(np.isnan(srcraw[:,j4]).sum()),
                 'stale_hops_proxy_nonworsening_violations':int(np.sum(sensory[:,stale_idx]>origin_stale+1e-10)),
                 'mean_predicted_overall_change':float(np.mean(sensory[:,target.index('overall')]-pred(src)[:,target.index('overall')]))},
    'constraint_definition':'4 measured features numeric source upper bound, stale_hops Q1 estimated score source upper bound',
    'candidate_optimization':'100 draws from learned Tripel conditional distribution plus OT candidate; 5 predeclared convex blending factors; minimize Tripel latent distance + .15 source shift subject to all 5 constraints and source shift<6 latent units'}
 (o/'q3_transfer_optimization.json').write_text(json.dumps(s,indent=2,ensure_ascii=False))
 summary=json.loads((o/'q3_summary.json').read_text());summary['optimized_transfer']=s
 (o/'q3_summary.json').write_text(json.dumps(summary,indent=2,ensure_ascii=False))
 print(json.dumps(s,ensure_ascii=False,indent=2),flush=True)
if __name__=='__main__':main()
